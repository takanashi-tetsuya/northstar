CREATE FUNCTION northstar_user_set_status_api(
    requested_actor_id UUID,
    expected_actor_generation BIGINT,
    requested_session_hash BYTEA,
    requested_target_id UUID,
    requested_disabled BOOLEAN,
    requested_admin BOOLEAN
) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE target_admin BOOLEAN; target_disabled BOOLEAN; previous_generation BIGINT;
BEGIN
    IF requested_disabled IS NULL AND requested_admin IS NULL THEN
        RAISE EXCEPTION 'empty account-status command' USING ERRCODE='22023';
    END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(5645368709120101);
    PERFORM id FROM users WHERE id=ANY(ARRAY[requested_actor_id,requested_target_id])
      ORDER BY id FOR UPDATE;
    PERFORM 1 FROM users actor JOIN api_sessions session ON session.user_id=actor.id
     WHERE actor.id=requested_actor_id
       AND actor.auth_generation=expected_actor_generation
       AND actor.is_admin AND NOT actor.is_disabled
       AND session.token_hash=requested_session_hash
       AND session.expires_at>pg_catalog.clock_timestamp()
     FOR UPDATE OF actor,session;
    IF NOT FOUND THEN RETURN -2; END IF;
    IF requested_actor_id=requested_target_id
       AND (requested_disabled IS TRUE OR requested_admin IS FALSE) THEN
        RETURN -3;
    END IF;
    SELECT is_admin,is_disabled,auth_generation
      INTO target_admin,target_disabled,previous_generation
      FROM users WHERE id=requested_target_id FOR UPDATE;
    IF NOT FOUND THEN RETURN -1; END IF;
    IF target_admin AND NOT target_disabled
       AND (
         NOT COALESCE(requested_admin,target_admin)
         OR COALESCE(requested_disabled,target_disabled)
       ) THEN
        IF (SELECT pg_catalog.count(*) FROM users
             WHERE is_admin AND NOT is_disabled)<=1 THEN
            RETURN -4;
        END IF;
    END IF;
    UPDATE users SET
        is_disabled=COALESCE(requested_disabled,is_disabled),
        is_admin=COALESCE(requested_admin,is_admin),
        auth_generation=auth_generation+CASE
          WHEN is_disabled IS DISTINCT FROM COALESCE(requested_disabled,is_disabled)
            OR is_admin IS DISTINCT FROM COALESCE(requested_admin,is_admin)
          THEN 1 ELSE 0 END
      WHERE id=requested_target_id;
    IF target_disabled IS DISTINCT FROM COALESCE(requested_disabled,target_disabled)
       OR target_admin IS DISTINCT FROM COALESCE(requested_admin,target_admin) THEN
        UPDATE fast_tokens SET revoked_at=pg_catalog.clock_timestamp()
         WHERE user_id=requested_target_id AND revoked_at IS NULL;
        DELETE FROM api_sessions WHERE user_id=requested_target_id;
        UPDATE sm_resume_sessions
           SET resumable=FALSE,live_lease_until=pg_catalog.clock_timestamp(),
               expires_at=pg_catalog.clock_timestamp(),updated_at=pg_catalog.clock_timestamp()
         WHERE user_id=requested_target_id;
    END IF;
    INSERT INTO audit_log(actor_id,action,target,details)
    VALUES(requested_actor_id,'admin.user.update',requested_target_id::TEXT,
           pg_catalog.jsonb_build_object(
             'disabled',requested_disabled,'admin',requested_admin,'source','rest'
           ));
    RETURN previous_generation;
END;
$$;

CREATE FUNCTION northstar_admin_create_user(
    requested_actor_id UUID, requested_actor_username TEXT,
    expected_actor_generation BIGINT, requested_id UUID, requested_username TEXT,
    requested_password_hash TEXT, requested_sha256_salt BYTEA,
    requested_iterations INTEGER, requested_sha256_stored_key BYTEA,
    requested_sha256_server_key BYTEA, requested_sha1_salt BYTEA,
    requested_sha1_iterations INTEGER, requested_sha1_stored_key BYTEA,
    requested_sha1_server_key BYTEA
) RETURNS TEXT
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
BEGIN
    IF NOT northstar_user_credentials_valid(
         requested_password_hash,requested_sha256_salt,requested_iterations,
         requested_sha256_stored_key,requested_sha256_server_key,
         requested_sha1_salt,requested_sha1_iterations,
         requested_sha1_stored_key,requested_sha1_server_key
       ) OR requested_username IS NULL
         OR octet_length(requested_username) NOT BETWEEN 1 AND 64 THEN
        RAISE EXCEPTION 'invalid administrative account-create command' USING ERRCODE='22023';
    END IF;
    -- Reject obvious stale/non-admin callers before taking capacity.  Do not
    -- hold a users row while acquiring the global account-capacity shard:
    -- account deletion deliberately orders those locks capacity -> users.
    PERFORM 1 FROM users WHERE id=requested_actor_id
      AND username=requested_actor_username
      AND auth_generation=expected_actor_generation
      AND is_admin AND NOT is_disabled;
    IF NOT FOUND THEN RETURN 'unauthorized'; END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(
      pg_catalog.hashtextextended(requested_username,0));
    IF EXISTS(SELECT 1 FROM users WHERE username=requested_username) THEN
        RETURN 'username_taken';
    END IF;
    IF northstar_capacity_acquire('account',requested_id) IS NULL THEN
        RETURN 'capacity_exhausted';
    END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(5645368709120101);
    PERFORM 1 FROM users WHERE id=requested_actor_id
      AND username=requested_actor_username
      AND auth_generation=expected_actor_generation
      AND is_admin AND NOT is_disabled FOR SHARE;
    IF NOT FOUND THEN
        PERFORM northstar_capacity_release('account',requested_id);
        RETURN 'unauthorized';
    END IF;
    INSERT INTO users(
        id,username,password_hash,is_admin,scram_sha256_salt,
        scram_sha256_iterations,scram_sha256_stored_key,scram_sha256_server_key,
        scram_sha1_salt,scram_sha1_iterations,scram_sha1_stored_key,scram_sha1_server_key
    ) VALUES(
        requested_id,requested_username,requested_password_hash,FALSE,
        requested_sha256_salt,requested_iterations,requested_sha256_stored_key,
        requested_sha256_server_key,requested_sha1_salt,requested_sha1_iterations,
        requested_sha1_stored_key,requested_sha1_server_key
    );
    INSERT INTO audit_log(actor_id,action,target,details)
    VALUES(requested_actor_id,'admin.user.add',requested_id::TEXT,
           pg_catalog.jsonb_build_object('username',requested_username,'source','xep-0133'));
    RETURN 'created';
END;
$$;

