CREATE FUNCTION northstar_admin_user_lifecycle(
    requested_actor_id UUID, requested_actor_username TEXT,
    expected_actor_generation BIGINT, requested_target_id UUID,
    expected_target_username TEXT, requested_action TEXT
) RETURNS TEXT
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE target_admin BOOLEAN; target_disabled BOOLEAN; desired_disabled BOOLEAN;
BEGIN
    IF requested_action NOT IN ('disable','reenable','end_sessions') THEN
        RAISE EXCEPTION 'invalid administrative lifecycle action' USING ERRCODE='22023';
    END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(5645368709120101);
    PERFORM id FROM users
     WHERE id=ANY(ARRAY[requested_actor_id,requested_target_id]) ORDER BY id FOR UPDATE;
    PERFORM 1 FROM users WHERE id=requested_actor_id
      AND username=requested_actor_username
      AND auth_generation=expected_actor_generation
      AND is_admin AND NOT is_disabled;
    IF NOT FOUND THEN RETURN 'unauthorized'; END IF;
    SELECT is_admin,is_disabled INTO target_admin,target_disabled FROM users
      WHERE id=requested_target_id AND username=expected_target_username;
    IF NOT FOUND THEN RETURN 'target_changed'; END IF;
    IF requested_action='disable' AND requested_actor_id=requested_target_id THEN
        RETURN 'self_mutation';
    END IF;
    IF requested_action='disable' AND target_admin AND NOT target_disabled
       AND (SELECT pg_catalog.count(*) FROM users
             WHERE is_admin AND NOT is_disabled)<=1 THEN
        RETURN 'last_administrator';
    END IF;
    IF requested_action IN ('disable','reenable') THEN
        desired_disabled := requested_action='disable';
        UPDATE users SET is_disabled=desired_disabled,
          auth_generation=auth_generation+1
          WHERE id=requested_target_id
            AND is_disabled IS DISTINCT FROM desired_disabled;
    ELSE
        UPDATE users SET auth_generation=auth_generation+1
          WHERE id=requested_target_id;
    END IF;
    IF FOUND THEN
      UPDATE fast_tokens SET revoked_at=pg_catalog.clock_timestamp()
        WHERE user_id=requested_target_id AND revoked_at IS NULL;
      DELETE FROM api_sessions WHERE user_id=requested_target_id;
      UPDATE sm_resume_sessions SET
          resumable=FALSE,live_lease_until=pg_catalog.clock_timestamp(),
          expires_at=pg_catalog.clock_timestamp(),updated_at=pg_catalog.clock_timestamp()
        WHERE user_id=requested_target_id;
    END IF;
    INSERT INTO audit_log(actor_id,action,target,details)
    VALUES(requested_actor_id,
      CASE WHEN requested_action='end_sessions' THEN 'admin.user.sessions.end'
           ELSE 'admin.user.update' END,
      requested_target_id::TEXT,
      pg_catalog.jsonb_build_object(
        'username',expected_target_username,'source','xep-0133',
        'disabled',CASE WHEN requested_action='disable' THEN TRUE
                        WHEN requested_action='reenable' THEN FALSE ELSE NULL END
      ));
    RETURN 'applied';
END;
$$;

CREATE FUNCTION northstar_admin_replace_users(
    requested_actor_id UUID, requested_actor_username TEXT,
    expected_actor_generation BIGINT, requested_admin_ids UUID[]
) RETURNS UUID[]
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE changed UUID[];
BEGIN
    IF requested_admin_ids IS NULL OR cardinality(requested_admin_ids)=0
       OR cardinality(requested_admin_ids)>200
       OR requested_actor_id<>ALL(requested_admin_ids) THEN
        RAISE EXCEPTION 'invalid administrator replacement set' USING ERRCODE='22023';
    END IF;
    IF (SELECT pg_catalog.count(DISTINCT candidate) FROM unnest(requested_admin_ids) candidate)
       <>cardinality(requested_admin_ids) THEN
        RAISE EXCEPTION 'duplicate administrator replacement identity' USING ERRCODE='22023';
    END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(5645368709120101);
    PERFORM id FROM users ORDER BY id FOR UPDATE;
    PERFORM 1 FROM users WHERE id=requested_actor_id
      AND username=requested_actor_username
      AND auth_generation=expected_actor_generation
      AND is_admin AND NOT is_disabled;
    IF NOT FOUND THEN RETURN NULL; END IF;
    IF (SELECT pg_catalog.count(*) FROM users
         WHERE id=ANY(requested_admin_ids) AND NOT is_disabled)
       <>cardinality(requested_admin_ids) THEN
        RAISE EXCEPTION 'administrator set contains unavailable account' USING ERRCODE='22023';
    END IF;
    WITH modified AS (
      UPDATE users SET is_admin=(id=ANY(requested_admin_ids)),
        auth_generation=auth_generation+1
       WHERE is_admin IS DISTINCT FROM (id=ANY(requested_admin_ids))
       RETURNING id
    ) SELECT COALESCE(pg_catalog.array_agg(id ORDER BY id),ARRAY[]::UUID[])
        INTO changed FROM modified;
    UPDATE fast_tokens SET revoked_at=pg_catalog.clock_timestamp()
      WHERE user_id=ANY(changed) AND revoked_at IS NULL;
    DELETE FROM api_sessions WHERE user_id=ANY(changed);
    UPDATE sm_resume_sessions SET
      resumable=FALSE,live_lease_until=pg_catalog.clock_timestamp(),
      expires_at=pg_catalog.clock_timestamp(),updated_at=pg_catalog.clock_timestamp()
      WHERE user_id=ANY(changed);
    INSERT INTO audit_log(actor_id,action,target,details)
    VALUES(requested_actor_id,'admin.list.replace',NULL,
      pg_catalog.jsonb_build_object('admin_ids',requested_admin_ids,'changed_ids',changed));
    RETURN changed;
END;
$$;

