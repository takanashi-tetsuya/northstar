-- Complete, positive table-level privilege manifest for the runtime login.
-- Every final public application table (plus sqlx's ledger) appears exactly
-- once, including tables on which runtime has no table privilege.  Column ACLs
-- are deliberately outside this table: sm_resume_sessions has one separately
-- attested non-secret SELECT column set.  A migration that creates or drops a
-- table must update this list, and the static checker proves the lifecycle and
-- origin against the migration corpus.
DROP TABLE IF EXISTS pg_temp.northstar_runtime_relation_manifest;
CREATE TEMPORARY TABLE northstar_runtime_relation_manifest (
  relation_name pg_catalog.text PRIMARY KEY
    CHECK (relation_name ~ '^[a-z_][a-z0-9_]*$'),
  can_select pg_catalog.bool NOT NULL,
  can_insert pg_catalog.bool NOT NULL,
  can_update pg_catalog.bool NOT NULL,
  can_delete pg_catalog.bool NOT NULL,
  origin pg_catalog.text NOT NULL
    CHECK (origin = 'sqlx' OR origin ~ '^[0-9]{4}$')
);

