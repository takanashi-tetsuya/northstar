/// Delivery boundary used by roster-item removal transactions.
///
/// A missing local account is still a valid routing result: cancellation
/// stanzas are generated by the state transition but have no connected or
/// durable local recipient. Remote delivery always uses the durable outbox.
#[derive(Clone, Copy, Debug)]
pub enum RosterRemovalRoute<'a> {
    Local {
        owner_jid: &'a str,
        /// Canonical localpart for a local account. Hosted services and
        /// vanished local contacts use `None` and have no reciprocal account
        /// transition.
        contact_username: Option<&'a str>,
    },
    Remote {
        target_domain: &'a str,
        unsubscribe_stanza: &'a str,
        unsubscribed_stanza: &'a str,
        bounce_to: Option<&'a str>,
        policy: super::S2sOutboxPolicy,
    },
}

