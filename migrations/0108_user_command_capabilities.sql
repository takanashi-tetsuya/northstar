    INSERT INTO audit_log(actor_id,action,target,details)
    VALUES(requested_actor_id,'admin.command.read',requested_node,
      pg_catalog.jsonb_build_object('session_id',locked_id));
    RETURN 'finished';
END;
$$;

CREATE FUNCTION northstar_admin_command_begin_execution(
    requested_bearer TEXT, requested_claim_token TEXT,
    requested_operation_id UUID, requested_actor_id UUID,
    requested_actor_username TEXT, requested_owner_full_jid TEXT,
    expected_actor_generation BIGINT, requested_node TEXT,
    requested_target_digest BYTEA
) RETURNS TABLE(outcome TEXT, operation_id UUID, result_payload TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE locked admin_command_sessions%ROWTYPE; keyed_target BYTEA;
BEGIN
    outcome := 'invalid'; operation_id := NULL; result_payload := NULL;
    IF requested_operation_id IS NULL
       OR requested_bearer IS NULL OR requested_claim_token IS NULL
       OR octet_length(requested_bearer) NOT BETWEEN 43 AND 256
       OR octet_length(requested_claim_token) NOT BETWEEN 43 AND 256
       OR octet_length(requested_target_digest)<>32
       OR NOT northstar_admin_command_node_valid(requested_node) THEN
      RETURN NEXT; RETURN;
    END IF;
    keyed_target := northstar_admin_command_target_hash(requested_target_digest);
    SELECT * INTO locked FROM admin_command_sessions
     WHERE bearer_hash=northstar_admin_command_bearer_hash(
       requested_bearer,requested_actor_id,requested_actor_username,
       expected_actor_generation,requested_owner_full_jid,requested_node)
       AND owner_id=requested_actor_id AND owner_full_jid=requested_owner_full_jid
       AND owner_auth_generation=expected_actor_generation AND node=requested_node
     FOR UPDATE;
    IF NOT FOUND THEN RETURN NEXT; RETURN; END IF;
    IF locked.expires_at<=pg_catalog.clock_timestamp() THEN
      IF locked.completed_at IS NULL THEN
        UPDATE admin_command_sessions
           SET completed_at=pg_catalog.clock_timestamp(),stage='expired',
               claim_hash=NULL,claim_expires_at=NULL,updated_at=pg_catalog.clock_timestamp()
         WHERE id=locked.id;
      END IF;
      outcome := 'expired'; RETURN NEXT; RETURN;
    END IF;
    -- A completed result is replayable only while the exact administrator
    -- incarnation that created it is still current.  Checking this before the
    -- cached-result and busy branches prevents a demoted, disabled, deleted or
    -- credential-rotated bearer from becoming a read capability.
    PERFORM 1 FROM users
     WHERE id=requested_actor_id AND username=requested_actor_username
       AND auth_generation=expected_actor_generation
       AND is_admin AND NOT is_disabled FOR UPDATE;
    IF NOT FOUND THEN RETURN NEXT; RETURN; END IF;
    IF locked.result_payload IS NOT NULL THEN
      IF locked.request_digest=keyed_target THEN
        outcome := 'completed'; operation_id := locked.operation_id;
        result_payload := locked.result_payload;
      END IF;
      RETURN NEXT; RETURN;
    END IF;
    IF locked.completed_at IS NOT NULL THEN RETURN NEXT; RETURN; END IF;
    IF locked.stage='executing' AND locked.claim_hash IS NOT NULL
       AND locked.claim_expires_at>pg_catalog.clock_timestamp() THEN
      IF locked.request_digest=keyed_target THEN outcome := 'busy'; END IF;
      RETURN NEXT; RETURN;
    END IF;
    UPDATE admin_command_sessions
       SET stage='executing',operation_id=requested_operation_id,
           request_digest=keyed_target,
           claim_hash=northstar_admin_command_claim_hash(
             requested_claim_token,requested_actor_id,requested_actor_username,
             expected_actor_generation,requested_node,requested_target_digest),
           claim_expires_at=pg_catalog.clock_timestamp()+INTERVAL '2 minutes',
           execution_started_at=pg_catalog.clock_timestamp(),
           updated_at=pg_catalog.clock_timestamp()
     WHERE id=locked.id;
    outcome := 'started'; operation_id := requested_operation_id;
    RETURN NEXT;
END;
$$;

