CREATE FUNCTION northstar_admin_command_set_service_message(
    requested_claim_token TEXT, requested_actor_id UUID,
    requested_actor_username TEXT, expected_actor_generation BIGINT,
    requested_node TEXT, requested_target_digest BYTEA,
    requested_kind TEXT, requested_body TEXT, requested_payload TEXT
) RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE locked_id UUID; expected_kind TEXT;
BEGIN
    expected_kind := CASE requested_node
      WHEN 'http://jabber.org/protocol/admin#set-motd' THEN 'motd'
      WHEN 'http://jabber.org/protocol/admin#edit-motd' THEN 'motd'
      WHEN 'http://jabber.org/protocol/admin#delete-motd' THEN 'motd'
      WHEN 'http://jabber.org/protocol/admin#set-welcome' THEN 'welcome'
      WHEN 'http://jabber.org/protocol/admin#delete-welcome' THEN 'welcome'
      ELSE NULL END;
    IF expected_kind IS NULL OR requested_kind<>expected_kind
       OR (requested_body IS NOT NULL
           AND (octet_length(requested_body)<1 OR octet_length(requested_body)>65536))
       OR (requested_node IN (
             'http://jabber.org/protocol/admin#delete-motd',
             'http://jabber.org/protocol/admin#delete-welcome')
           AND requested_body IS NOT NULL)
       OR (requested_node NOT IN (
             'http://jabber.org/protocol/admin#delete-motd',
             'http://jabber.org/protocol/admin#delete-welcome')
           AND requested_body IS NULL) THEN
      RETURN FALSE;
    END IF;
    locked_id := northstar_admin_command_lock_claim(
      requested_claim_token,requested_actor_id,requested_actor_username,
      expected_actor_generation,requested_node,requested_target_digest);
    IF locked_id IS NULL THEN RETURN FALSE; END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(
      pg_catalog.hashtextextended('northstar:admin-service-message:' || requested_kind,0));
    IF requested_body IS NULL THEN
      DELETE FROM admin_service_messages WHERE kind=requested_kind;
    ELSE
      INSERT INTO admin_service_messages(kind,body,revision,updated_by)
      VALUES(requested_kind,requested_body,pg_catalog.gen_random_uuid(),requested_actor_id)
      ON CONFLICT(kind) DO UPDATE SET
        body=EXCLUDED.body,revision=EXCLUDED.revision,updated_by=EXCLUDED.updated_by,
        updated_at=pg_catalog.clock_timestamp();
    END IF;
    INSERT INTO audit_log(actor_id,action,target,details)
    VALUES(
      requested_actor_id,
      CASE WHEN requested_body IS NULL
        THEN 'admin.service_message.delete' ELSE 'admin.service_message.set' END,
      requested_kind,
      pg_catalog.jsonb_build_object('bytes',octet_length(requested_body)));
    RETURN northstar_admin_command_complete_locked(
      locked_id,requested_actor_id,requested_node,requested_payload,'admin.command.execute');
END;
$$;

