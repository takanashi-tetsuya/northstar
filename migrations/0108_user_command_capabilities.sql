CREATE FUNCTION northstar_user_consume_recovery_generation(
    requested_id UUID, expected_auth_generation BIGINT,
    requested_session_hash BYTEA
) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE next_generation BIGINT;
BEGIN
    PERFORM 1 FROM users account JOIN api_sessions session ON session.user_id=account.id
      WHERE account.id=requested_id
