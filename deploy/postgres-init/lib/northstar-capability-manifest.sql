-- Canonical SECURITY DEFINER capability and runtime-relation manifests for
-- the public application schema.  This file is data, not a reflection of the
-- database's current grants: grant reconciliation, startup/upgrade audits and
-- database CI all consume it independently and compare it with pg_catalog.
--
-- `workload` is the only login that may execute the routine.  `private`
-- means no Northstar workload login (runtime, command issuer or backup) may
-- execute it.  `origin` lets the static checker prove that the independently
-- maintained migration-local security manifests remain in lock-step.

DROP TABLE IF EXISTS pg_temp.northstar_capability_manifest;
CREATE TEMPORARY TABLE northstar_capability_manifest (
  signature pg_catalog.text PRIMARY KEY,
  workload pg_catalog.text NOT NULL
    CHECK (workload IN ('runtime','command','private')),
  origin pg_catalog.text NOT NULL
    CHECK (origin IN ('baseline-0111','0112','0113','0114','0126','0127','0128'))
);

