CREATE FUNCTION northstar_admin_command_lock_claim(
    requested_claim_token TEXT,
    requested_actor_id UUID,
    requested_actor_username TEXT,
    expected_actor_generation BIGINT,
    requested_node TEXT,
    requested_target_digest BYTEA
) RETURNS UUID
LANGUAGE plpgsql SET search_path FROM CURRENT
AS $$
DECLARE
    locked_session UUID;
BEGIN
    IF requested_claim_token IS NULL
       OR octet_length(requested_claim_token) NOT BETWEEN 43 AND 256
       OR octet_length(requested_target_digest)<>32
       OR NOT northstar_admin_command_node_valid(requested_node) THEN
      RETURN NULL;
    END IF;
    SELECT id INTO locked_session
      FROM admin_command_sessions
     WHERE claim_hash=northstar_admin_command_claim_hash(
             requested_claim_token,requested_actor_id,requested_actor_username,
             expected_actor_generation,requested_node,requested_target_digest)
       AND owner_id=requested_actor_id
       AND owner_auth_generation=expected_actor_generation
       AND node=requested_node
       AND request_digest=northstar_admin_command_target_hash(requested_target_digest)
       AND stage='executing' AND completed_at IS NULL
       AND expires_at>pg_catalog.clock_timestamp()
       AND claim_expires_at>pg_catalog.clock_timestamp()
     FOR UPDATE;
    IF locked_session IS NULL THEN RETURN NULL; END IF;
    PERFORM 1 FROM users
     WHERE id=requested_actor_id
       AND username=requested_actor_username
       AND auth_generation=expected_actor_generation
       AND is_admin AND NOT is_disabled
     FOR UPDATE;
    IF NOT FOUND THEN RETURN NULL; END IF;
    RETURN locked_session;
END;
$$;

CREATE FUNCTION northstar_admin_command_complete_locked(
    requested_session_id UUID,
    requested_actor_id UUID,
    requested_node TEXT,
    requested_payload TEXT,
    requested_audit_action TEXT
) RETURNS BOOLEAN
LANGUAGE plpgsql SET search_path FROM CURRENT
AS $$
BEGIN
    IF requested_session_id IS NULL
       OR requested_payload IS NULL OR octet_length(requested_payload)>1048576
       OR requested_audit_action NOT IN ('admin.command.read','admin.command.execute') THEN
      RETURN FALSE;
    END IF;
    UPDATE admin_command_sessions
       SET completed_at=pg_catalog.clock_timestamp(),stage='completed',
           result_payload=requested_payload,claim_hash=NULL,claim_expires_at=NULL,
           updated_at=pg_catalog.clock_timestamp()
     WHERE id=requested_session_id AND stage='executing'
       AND completed_at IS NULL AND claim_hash IS NOT NULL;
    IF NOT FOUND THEN RETURN FALSE; END IF;
    INSERT INTO audit_log(actor_id,action,target,details)
    VALUES(requested_actor_id,requested_audit_action,requested_node,
      pg_catalog.jsonb_build_object('session_id',requested_session_id));
    RETURN TRUE;
END;
$$;

CREATE FUNCTION northstar_admin_command_create_session(
    requested_id UUID, requested_bearer TEXT,
    requested_actor_id UUID, requested_actor_username TEXT,
    requested_owner_full_jid TEXT, requested_server_domain TEXT,
    expected_actor_generation BIGINT, requested_node TEXT, requested_stage TEXT
) RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE active_global BIGINT; active_owner BIGINT;
BEGIN
    IF requested_id IS NULL OR requested_actor_id IS NULL
       OR requested_bearer IS NULL
       OR octet_length(requested_bearer) NOT BETWEEN 43 AND 256
       OR requested_actor_username IS NULL
       OR octet_length(requested_actor_username) NOT BETWEEN 1 AND 64
       OR requested_owner_full_jid IS NULL
       OR octet_length(requested_owner_full_jid) NOT BETWEEN 3 AND 3071
       OR requested_server_domain IS NULL
       OR octet_length(requested_server_domain) NOT BETWEEN 1 AND 253
       OR requested_stage NOT IN ('form','executing')
       OR NOT northstar_admin_command_node_valid(requested_node)
       OR pg_catalog.split_part(requested_owner_full_jid,'/',1)
          <>requested_actor_username || '@' || requested_server_domain THEN
      RETURN FALSE;
    END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(5645368709120133);
    DELETE FROM admin_command_sessions WHERE id IN (
      SELECT id FROM admin_command_sessions
       WHERE (completed_at IS NOT NULL
              AND completed_at<pg_catalog.clock_timestamp()-INTERVAL '10 minutes')
          OR expires_at<pg_catalog.clock_timestamp()-INTERVAL '10 minutes'
       ORDER BY COALESCE(completed_at,expires_at),id LIMIT 1000
    );
    PERFORM 1 FROM users
     WHERE id=requested_actor_id AND username=requested_actor_username
       AND auth_generation=expected_actor_generation
       AND is_admin AND NOT is_disabled FOR SHARE;
    IF NOT FOUND THEN RETURN FALSE; END IF;
    SELECT pg_catalog.count(*),
           pg_catalog.count(*) FILTER(WHERE owner_id=requested_actor_id)
      INTO active_global,active_owner FROM admin_command_sessions
     WHERE completed_at IS NULL AND expires_at>pg_catalog.clock_timestamp();
    IF active_global>=1000 OR active_owner>=8 THEN RETURN FALSE; END IF;
    INSERT INTO admin_command_sessions(
      id,owner_id,owner_full_jid,owner_auth_generation,node,stage,
      expires_at,bearer_hash
    ) VALUES(
      requested_id,requested_actor_id,requested_owner_full_jid,
      expected_actor_generation,requested_node,requested_stage,
      pg_catalog.clock_timestamp()+INTERVAL '10 minutes',
      northstar_admin_command_bearer_hash(
        requested_bearer,requested_actor_id,requested_actor_username,
        expected_actor_generation,requested_owner_full_jid,requested_node)
    );
    RETURN TRUE;
END;
$$;

CREATE FUNCTION northstar_admin_command_finish_session(
    requested_bearer TEXT, requested_actor_id UUID,
    requested_actor_username TEXT, requested_owner_full_jid TEXT,
    expected_actor_generation BIGINT, requested_node TEXT,
    requested_final_stage TEXT
) RETURNS TEXT
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE locked_id UUID; deadline TIMESTAMPTZ;
BEGIN
    IF requested_final_stage<>'canceled' THEN RETURN 'invalid'; END IF;
    SELECT id,expires_at INTO locked_id,deadline FROM admin_command_sessions
     WHERE bearer_hash=northstar_admin_command_bearer_hash(
       requested_bearer,requested_actor_id,requested_actor_username,
       expected_actor_generation,requested_owner_full_jid,requested_node)
       AND owner_id=requested_actor_id AND owner_full_jid=requested_owner_full_jid
       AND owner_auth_generation=expected_actor_generation
       AND node=requested_node AND completed_at IS NULL FOR UPDATE;
    IF locked_id IS NULL THEN RETURN 'invalid'; END IF;
    IF deadline<=pg_catalog.clock_timestamp() THEN
      UPDATE admin_command_sessions
         SET completed_at=pg_catalog.clock_timestamp(),stage='expired',
             claim_hash=NULL,claim_expires_at=NULL,updated_at=pg_catalog.clock_timestamp()
       WHERE id=locked_id;
      RETURN 'expired';
    END IF;
    PERFORM 1 FROM users
     WHERE id=requested_actor_id AND username=requested_actor_username
       AND auth_generation=expected_actor_generation
       AND is_admin AND NOT is_disabled FOR UPDATE;
    IF NOT FOUND THEN RETURN 'invalid'; END IF;
    UPDATE admin_command_sessions
       SET completed_at=pg_catalog.clock_timestamp(),stage='canceled',
           claim_hash=NULL,claim_expires_at=NULL,updated_at=pg_catalog.clock_timestamp()
     WHERE id=locked_id;
    RETURN 'finished';
END;
$$;

CREATE FUNCTION northstar_admin_command_complete_immediate_read(
    requested_bearer TEXT, requested_actor_id UUID,
    requested_actor_username TEXT, requested_owner_full_jid TEXT,
    expected_actor_generation BIGINT, requested_node TEXT,
    requested_payload TEXT
) RETURNS TEXT
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE locked_id UUID; deadline TIMESTAMPTZ;
BEGIN
    IF requested_payload IS NULL OR octet_length(requested_payload)>1048576 THEN
      RETURN 'invalid';
    END IF;
    SELECT id,expires_at INTO locked_id,deadline FROM admin_command_sessions
     WHERE bearer_hash=northstar_admin_command_bearer_hash(
       requested_bearer,requested_actor_id,requested_actor_username,
       expected_actor_generation,requested_owner_full_jid,requested_node)
       AND owner_id=requested_actor_id AND owner_full_jid=requested_owner_full_jid
       AND owner_auth_generation=expected_actor_generation
       AND node=requested_node AND stage='executing' AND completed_at IS NULL
     FOR UPDATE;
    IF locked_id IS NULL THEN RETURN 'invalid'; END IF;
    IF deadline<=pg_catalog.clock_timestamp() THEN
      UPDATE admin_command_sessions
         SET completed_at=pg_catalog.clock_timestamp(),stage='expired',
             updated_at=pg_catalog.clock_timestamp() WHERE id=locked_id;
      RETURN 'expired';
    END IF;
    PERFORM 1 FROM users
     WHERE id=requested_actor_id AND username=requested_actor_username
