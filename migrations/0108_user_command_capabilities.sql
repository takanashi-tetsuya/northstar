CREATE FUNCTION northstar_user_quiesce_deletion(
    requested_id UUID, expected_auth_generation BIGINT
) RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE disabled BOOLEAN; current_generation BIGINT;
BEGIN
    SELECT is_disabled,auth_generation INTO disabled,current_generation
      FROM users WHERE id=requested_id FOR UPDATE;
    IF NOT FOUND THEN RETURN FALSE; END IF;
    IF disabled THEN
        RETURN EXISTS(SELECT 1 FROM account_deletion_requests WHERE user_id=requested_id);
    END IF;
    IF current_generation<>expected_auth_generation THEN RETURN FALSE; END IF;
    UPDATE users SET is_disabled=TRUE,auth_generation=auth_generation+1
      WHERE id=requested_id;
    DELETE FROM api_sessions WHERE user_id=requested_id;
    UPDATE fast_tokens SET revoked_at=COALESCE(revoked_at,pg_catalog.clock_timestamp())
      WHERE user_id=requested_id;
    UPDATE sm_resume_sessions SET
      resumable=FALSE,live_lease_until=pg_catalog.clock_timestamp(),
      expires_at=pg_catalog.clock_timestamp(),updated_at=pg_catalog.clock_timestamp()
      WHERE user_id=requested_id;
    INSERT INTO account_deletion_requests(user_id) VALUES(requested_id)
      ON CONFLICT(user_id) DO NOTHING;
    INSERT INTO audit_log(actor_id,action,target,details)
    VALUES(requested_id,'user.account.quiesce',requested_id::TEXT,'{}'::JSONB);
    RETURN TRUE;
END;
$$;

