-- Least-authority account command capabilities.
--
-- The long-lived runtime role may read account authority, but it must never
-- receive INSERT/UPDATE/DELETE on `users`.  Every mutation below is a fixed,
-- typed business command with its own authorization and compare-and-swap
-- fence.  There is deliberately no dynamic SQL, caller-selected column name,
-- JSON patch document, writable view, or custom-GUC authority channel.

-- XEP-0050/XEP-0133 uses a separate, capability-only PostgreSQL login.  The
-- long-lived runtime role has no access to this key or to the session table.
-- Bearers are generated by the application, returned to the XMPP client, and
-- never stored verbatim: only an HMAC made with this migrator-owned key is
-- durable.  Replacing a deployment therefore invalidates neither active
-- commands nor in-flight claims, while a leaked runtime SQL primitive cannot
-- mint a command merely by reading an administrator row.
CREATE TABLE admin_command_capability_authority (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    hmac_key BYTEA NOT NULL CHECK (octet_length(hmac_key)=32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

INSERT INTO admin_command_capability_authority(singleton,hmac_key)
VALUES(
    TRUE,
    pg_catalog.sha256(
      pg_catalog.uuid_send(pg_catalog.gen_random_uuid()) ||
      pg_catalog.uuid_send(pg_catalog.gen_random_uuid())
    )
);

-- Command sessions are process-ephemeral control-plane state.  A deployment
-- cannot safely carry pre-capability plaintext session identifiers across the
-- authority cutover, so invalidate the bounded (ten-minute) legacy set before
-- making the keyed representation mandatory.
DELETE FROM admin_command_sessions;
ALTER TABLE admin_command_sessions
    ADD COLUMN bearer_hash BYTEA NOT NULL CHECK (octet_length(bearer_hash)=32),
    ADD COLUMN claim_hash BYTEA CHECK (claim_hash IS NULL OR octet_length(claim_hash)=32),
    ADD COLUMN claim_expires_at TIMESTAMPTZ,
    ADD CONSTRAINT admin_command_claim_shape_check CHECK (
      (claim_hash IS NULL AND claim_expires_at IS NULL)
      OR
      (claim_hash IS NOT NULL AND claim_expires_at IS NOT NULL
       AND operation_id IS NOT NULL AND request_digest IS NOT NULL
       AND execution_started_at IS NOT NULL AND stage='executing')
    );
CREATE UNIQUE INDEX admin_command_sessions_bearer_hash_idx
    ON admin_command_sessions(bearer_hash);
CREATE UNIQUE INDEX admin_command_sessions_claim_hash_idx
    ON admin_command_sessions(claim_hash) WHERE claim_hash IS NOT NULL;

CREATE FUNCTION northstar_admin_command_hmac(payload BYTEA) RETURNS BYTEA
LANGUAGE plpgsql STABLE SET search_path FROM CURRENT
AS $$
DECLARE
    secret BYTEA;
    inner_pad BYTEA := pg_catalog.decode(pg_catalog.repeat('36',64),'hex');
    outer_pad BYTEA := pg_catalog.decode(pg_catalog.repeat('5c',64),'hex');
    index INTEGER;
BEGIN
    SELECT hmac_key INTO STRICT secret
      FROM admin_command_capability_authority WHERE singleton;
    FOR index IN 0..31 LOOP
      inner_pad := pg_catalog.set_byte(
        inner_pad,index,
        pg_catalog.get_byte(inner_pad,index) # pg_catalog.get_byte(secret,index)
      );
      outer_pad := pg_catalog.set_byte(
        outer_pad,index,
        pg_catalog.get_byte(outer_pad,index) # pg_catalog.get_byte(secret,index)
      );
    END LOOP;
    RETURN pg_catalog.sha256(outer_pad || pg_catalog.sha256(inner_pad || payload));
END;
$$;

