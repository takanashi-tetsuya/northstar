    expected_kind := CASE requested_node
      WHEN 'http://jabber.org/protocol/admin#edit-blacklist' THEN 'blacklist'
      WHEN 'http://jabber.org/protocol/admin#edit-whitelist' THEN 'whitelist'
      ELSE NULL END;
    IF expected_kind IS NULL OR requested_kind<>expected_kind
       OR requested_domains IS NULL OR cardinality(requested_domains)>1000
       OR EXISTS(SELECT 1 FROM pg_catalog.unnest(requested_domains) value
                  WHERE value IS NULL OR octet_length(value) NOT BETWEEN 1 AND 3071)
       OR (SELECT pg_catalog.count(DISTINCT value)
             FROM pg_catalog.unnest(requested_domains) value)
          <>cardinality(requested_domains) THEN
      RETURN;
    END IF;
    locked_id := northstar_admin_command_lock_claim(
      requested_claim_token,requested_actor_id,requested_actor_username,
      expected_actor_generation,requested_node,requested_target_digest);
    IF locked_id IS NULL THEN RETURN; END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(
      pg_catalog.hashtextextended('northstar:federation-runtime-rules:' || requested_kind,0));
    DELETE FROM federation_runtime_rules WHERE kind=requested_kind;
    INSERT INTO federation_runtime_rules(kind,domain,updated_by)
      SELECT requested_kind,value,requested_actor_id
        FROM pg_catalog.unnest(requested_domains) value ORDER BY value;
    INSERT INTO audit_log(actor_id,action,target,details)
    VALUES(requested_actor_id,'admin.federation_rules.replace',requested_kind,
      pg_catalog.jsonb_build_object('count',cardinality(requested_domains)));
    SELECT COALESCE(pg_catalog.array_agg(domain ORDER BY domain)
                      FILTER(WHERE kind='blacklist'),ARRAY[]::TEXT[]),
           COALESCE(pg_catalog.array_agg(domain ORDER BY domain)
                      FILTER(WHERE kind='whitelist'),ARRAY[]::TEXT[])
      INTO blacklist,whitelist FROM federation_runtime_rules;
    IF cardinality(blacklist)+cardinality(whitelist)>2000 THEN
      RAISE EXCEPTION 'federation rule snapshot exceeds bound' USING ERRCODE='54000';
    END IF;
    IF NOT northstar_admin_command_complete_locked(
         locked_id,requested_actor_id,requested_node,requested_payload,
         'admin.command.execute') THEN
      RAISE EXCEPTION 'command completion fence changed' USING ERRCODE='40001';
    END IF;
    RETURN NEXT;
END;
$$;

CREATE FUNCTION northstar_admin_command_service_control(
    requested_claim_token TEXT, requested_actor_id UUID,
    requested_actor_username TEXT, expected_actor_generation BIGINT,
    requested_node TEXT, requested_target_digest BYTEA,
    requested_action TEXT, requested_delay_seconds INTEGER,
    requested_announcement TEXT, requested_cancel BOOLEAN,
    requested_payload TEXT
) RETURNS UUID
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE locked_id UUID; generation UUID; expected_action TEXT;
BEGIN
    expected_action := CASE requested_node
      WHEN 'http://jabber.org/protocol/admin#restart' THEN 'restart'
      WHEN 'http://jabber.org/protocol/admin#shutdown' THEN 'shutdown'
      ELSE NULL END;
    IF expected_action IS NULL OR requested_action<>expected_action
       OR (NOT requested_cancel AND requested_delay_seconds NOT BETWEEN 5 AND 3600)
       OR requested_announcement IS NOT NULL
          AND octet_length(requested_announcement)>65536 THEN
      RETURN NULL;
    END IF;
    locked_id := northstar_admin_command_lock_claim(
      requested_claim_token,requested_actor_id,requested_actor_username,
      expected_actor_generation,requested_node,requested_target_digest);
    IF locked_id IS NULL THEN RETURN NULL; END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(5645368709120134);
    IF requested_cancel THEN
      UPDATE admin_service_control
         SET status='canceled',updated_at=pg_catalog.clock_timestamp()
       WHERE singleton AND status='scheduled'
         AND execute_at>pg_catalog.clock_timestamp()
       RETURNING admin_service_control.generation INTO generation;
      INSERT INTO audit_log(actor_id,action,target,details)
      VALUES(requested_actor_id,'admin.service_control.cancel',NULL,
        pg_catalog.jsonb_build_object('generation',generation));
    ELSE
      IF EXISTS(SELECT 1 FROM admin_service_control
         WHERE singleton AND status IN ('scheduled','fired')
           AND expires_at>pg_catalog.clock_timestamp() FOR UPDATE) THEN
        RETURN NULL;
      END IF;
      generation := pg_catalog.gen_random_uuid();
      INSERT INTO admin_service_control(
        singleton,generation,action,status,execute_at,expires_at,
        requested_by,requested_generation
      ) VALUES(
        TRUE,generation,requested_action,'scheduled',
        pg_catalog.clock_timestamp()+(requested_delay_seconds*INTERVAL '1 second'),
        pg_catalog.clock_timestamp()+((requested_delay_seconds+300)*INTERVAL '1 second'),
        requested_actor_id,expected_actor_generation
      ) ON CONFLICT(singleton) DO UPDATE SET
        generation=EXCLUDED.generation,action=EXCLUDED.action,status='scheduled',
        execute_at=EXCLUDED.execute_at,fired_at=NULL,expires_at=EXCLUDED.expires_at,
        requested_by=EXCLUDED.requested_by,
        requested_generation=EXCLUDED.requested_generation,
        created_at=pg_catalog.clock_timestamp(),updated_at=pg_catalog.clock_timestamp();
      INSERT INTO audit_log(actor_id,action,target,details)
      VALUES(requested_actor_id,'admin.service_control.request',requested_action,
        pg_catalog.jsonb_build_object(
          'generation',generation,'delay_seconds',requested_delay_seconds,
          'announcement_bytes',octet_length(requested_announcement)));
    END IF;
    IF NOT northstar_admin_command_complete_locked(
         locked_id,requested_actor_id,requested_node,requested_payload,
         'admin.command.execute') THEN
      RAISE EXCEPTION 'command completion fence changed' USING ERRCODE='40001';
    END IF;
    RETURN COALESCE(generation,'00000000-0000-0000-0000-000000000000'::UUID);
END;
$$;

-- The runtime watcher may observe and atomically fire a scheduled generation,
-- but it never receives UPDATE on the underlying control table.  This keeps an
-- arbitrary runtime SQL primitive from fabricating, accelerating, canceling or
-- rewriting a restart/shutdown request.
CREATE FUNCTION northstar_admin_service_control_poll()
RETURNS TABLE(
    generation UUID,
    action TEXT,
    execute_at TIMESTAMPTZ,
    fired_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ
)
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT
AS $$
DECLARE locked admin_service_control%ROWTYPE; observed_at TIMESTAMPTZ;
BEGIN
    SELECT * INTO locked FROM admin_service_control WHERE singleton FOR UPDATE;
    IF NOT FOUND THEN RETURN; END IF;
    observed_at := pg_catalog.clock_timestamp();
    IF locked.expires_at<=observed_at OR locked.status='canceled' THEN RETURN; END IF;
    IF locked.status='scheduled' AND locked.execute_at<=observed_at THEN
      UPDATE admin_service_control SET
        status='fired',fired_at=observed_at,updated_at=observed_at
       WHERE singleton AND status='scheduled'
       RETURNING * INTO locked;
    ELSIF locked.status<>'fired' THEN
      RETURN;
    END IF;
    generation := locked.generation;
    action := locked.action;
    execute_at := locked.execute_at;
    fired_at := locked.fired_at;
    expires_at := locked.expires_at;
    RETURN NEXT;
END;
$$;

